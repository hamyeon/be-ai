package com.vintic.backend.recommendation.domain;

// 유저 행동의 종류. 추천에서 취향 신호로 쓰는 가중치가 종류마다 다르다
// (입찰 > 찜 > 조회 순으로 취향을 강하게 드러낸다고 본다).
public enum ActivityType {

    // 경매 상세 조회. 가장 흔하지만 신호는 약하다 - 새로고침·봇도 섞인다.
    VIEW,

    // 찜하기. 찜 API가 아직 없어 당분간 쌓이지 않지만, 스키마에 미리 자리를 둔다.
    LIKE,

    // 입찰. 돈이 걸린 행동이라 취향을 가장 강하게 드러낸다.
    BID,

    // 화면 체류 시간. 서버가 알 수 없어 프론트가 보내줘야 하므로 수집은 나중에 붙인다.
    DWELL
}
