# 매물 설명에서 구성품 상태(FULL/PARTIAL/NONE)를 추정한다.
#
# 크롤링 시점의 box_included_guess(normalize.py)는 "박스"/"box"라는 글자가 있어야만
# 판정하고, 그마저도 앞뒤 좁은 창에 있/없/포함이 붙어 있어야 한다. 그래서 46,146건 중
# 4,933건(10.7%)만 판정되고 나머지는 전부 None이다. 실제 설명을 읽어보면
# "박스도 같이 드려요", "상자와 포장 그대로", "구성품은 신발 단품입니다",
# "끈 없고 신발 단품만" 처럼 말로 적은 매물이 훨씬 많다.
#
# 상태 등급에서 fine_condition.py가 한 것과 같은 접근이다 - 크롤링 시점 guess는
# 그대로 두고, 저장된 설명 텍스트를 다시 읽어 계수 산출용으로만 정밀 분류한다.
# 재크롤링이 필요 없다.
#
# 3단계로 나누는 이유는 백엔드 componentStatus가 FULL/PARTIAL/NONE 3값이기 때문이다.
# 지금까지 PARTIAL은 측정 대상 자체가 없었다(크롤러가 박스 유/무 2진값만 냈다).
#
#   NONE    : 박스가 없다. "신발만", "단품", "박스 없어요", "박스 분실"
#   FULL    : 박스 + 그 외 구성품(더스트백/여분끈/택/보증서)까지 있다. "풀박", "미개봉",
#             "박스와 구성품 모두", "박스, 더스트백 포함"
#   PARTIAL : 박스는 있는데 나머지는 없거나 언급이 없다. "박스 포함", "더스트백은 분실"
#
# 분류 순서가 곧 우선순위다: 없음 명시 > 전부 명시 > 박스만.
# "박스, 더스트백 분실하였지만"처럼 없음과 구성품 단어가 같이 나오는 매물은
# 없음이 가격을 지배한다.
import re

# ---------------------------------------------------------------------------
# 판정 전에 지우는 것들
# ---------------------------------------------------------------------------

# '택'은 13,388건에 나오는데 거의 전부 택배다. 구성품의 택(tag)으로 읽으면
# 배송 안내문이 전부 FULL로 분류된다. 판정 전에 지운다.
# (실측: '택' 포함 13,388건 vs '택배' 계열을 지우고 남는 것은 극소수)
DELIVERY = re.compile(
    r'(반값|편의점|일반|무료|알뜰|국내|씨유|cu|gs25?|편)?\s*택배[가-힣]*'
    r'|택배[비값]|편택|반택|택\s*[+＋]\s*\d|문고리|직거래|퀵배송',
    re.IGNORECASE)

# "박스 없어요"의 '없'을 보기 전에 "하자 없는 박스" 같은 표현이 끼면 안 되므로,
# 부정 판정은 박스 단어와의 거리로 제한한다(아래 NO_BOX 참고).

# 보호 용품·부속 판매 문구. "신발끈 판매합니다" 같은 매물은 애초에 신발이 아니다.
NOT_COMPONENT = re.compile(r'(신발|운동화)?\s*끈\s*(만\s*)?(판매|팝니다|삽니다)')

# ---------------------------------------------------------------------------
# NONE: 박스가 없다
# ---------------------------------------------------------------------------

BOX_WORD = r'(?:박스|상자|케이스|박구|box)'

# "박스 없어요", "박스는 없고", "박스 미포함", "박스 분실", "박스 버렸어요"
# 박스 단어와 부정어 사이에 10자까지 허용한다("박스, 더스트백 분실하였지만").
NO_BOX = re.compile(
    BOX_WORD + r'[^\.\n!?]{0,10}?(없|무|미포함|안\s*드|못\s*드|분실|버렸|버림|폐기|처분했)',
    re.IGNORECASE)

# "무박", "무박스", "박스x"
NO_BOX_SHORT = re.compile(r'무박스|무박(?![가-힣])|' + BOX_WORD + r'\s*[xX✕✖]')

# "신발만", "신발 단품", "본품만", "구성품은 신발 단품입니다"
SHOE_ONLY = re.compile(
    r'(신발|운동화|슈즈|본품|제품)\s*(만|단품)|단품\s*(만|입니다|이에요|예요)|'
    r'구성품\s*(은|는)?\s*(신발|본품|단품)')

# ---------------------------------------------------------------------------
# FULL: 박스 + 그 외 구성품
# ---------------------------------------------------------------------------

EXTRAS = r'(?:더스트\s*백?|여분\s*끈|여분\s*신발끈|스페어\s*끈|정품\s*택|택\s*택?|보증서|영수증|쇼핑백|슈트리|스트링)'

# "풀박", "풀박스", "풀구성"
FULL_WORD = re.compile(r'풀\s*박스?(?![가-힣])|풀\s*구성|풀셋|full\s*box', re.IGNORECASE)

# "미개봉", "새제품 그대로" - 박스와 구성품이 온전하다는 뜻으로 쓰인다
UNOPENED = re.compile(r'미개봉|개봉\s*안|뜯지\s*않|새\s*상품\s*그대로')

# "박스와 구성품 모두 있어요", "구성품 전부 포함"
ALL_COMPONENTS = re.compile(
    r'구성품\s*(을|를|도|은|는|과|와)?\s*(모두|전부|다|일체|그대로)'
    r'|(모두|전부|다)\s*(있|포함|드려|드립|보관)'
    r'|' + BOX_WORD + r'\s*(와|과|랑|,|\s)+\s*구성품')

# 박스 + 추가 구성품이 각각 언급된 경우 ("박스, 더스트백 포함입니다")
BOX_AND_EXTRA = re.compile(
    BOX_WORD + r'[^\.\n!?]{0,20}?' + EXTRAS + r'|' + EXTRAS + r'[^\.\n!?]{0,20}?' + BOX_WORD)

# ---------------------------------------------------------------------------
# PARTIAL: 박스는 있다
# ---------------------------------------------------------------------------

HAS_BOX = re.compile(
    BOX_WORD + r'[^\.\n!?]{0,12}?(있|포함|동봉|같이|함께|드려|드립|드릴|챙겨|보관|그대로|[oO○])'
    r'|(같이|함께|포함)[^\.\n!?]{0,6}?' + BOX_WORD)

# "더스트백은 분실", "끈은 없어요" - 박스 언급 없이 일부만 빠진 경우
SOME_MISSING = re.compile(
    EXTRAS + r'[^\.\n!?]{0,10}?(없|분실|미포함|안\s*드)'
    r'|구성품\s*(일부|중\s*일부)')

# 박스 언급 없이 구성품만 있다고 적은 경우 ("여분 끈이 포함되어 있어요").
# 구성품 일부가 확인됐지만 박스는 모르므로 PARTIAL이 맞다.
# 쇼핑백·영수증은 뺀다 - 포장·구매 증빙이라 구성품 판단의 근거가 약하다.
EXTRAS_STRONG = r'(?:더스트\s*백?|여분\s*끈|여분\s*신발끈|스페어\s*끈|보증서|슈트리)'
HAS_EXTRA = re.compile(EXTRAS_STRONG + r'[^\.\n!?]{0,10}?(있|포함|동봉|같이|함께|드려|드립|드릴)')


def classify(text):
    """설명에서 구성품 상태를 추정한다. 단서가 없으면 None.

    Returns: "FULL" | "PARTIAL" | "NONE" | None
    """
    if not text:
        return None

    text = DELIVERY.sub(" ", text)
    text = NOT_COMPONENT.sub(" ", text)

    # 1) 없음 명시가 가장 강한 신호다. "박스, 더스트백 분실하였지만 다른 더스트백을
    #    드릴게요" 같은 매물도 박스가 없는 것은 사실이다.
    if NO_BOX.search(text) or NO_BOX_SHORT.search(text) or SHOE_ONLY.search(text):
        return "NONE"

    # 2) 전부 있음
    if FULL_WORD.search(text) or UNOPENED.search(text):
        return "FULL"
    if ALL_COMPONENTS.search(text) or BOX_AND_EXTRA.search(text):
        return "FULL"

    # 3) 박스만 확인되거나, 일부가 빠졌다고 적은 경우
    if HAS_BOX.search(text) or SOME_MISSING.search(text) or HAS_EXTRA.search(text):
        return "PARTIAL"

    return None
