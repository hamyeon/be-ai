# 매물 설명에서 A/B/C 상태 등급을 추정한다.
#
# 크롤링 시점의 condition_grade_guess는 "새상품(DS/S)" 신호만 잡고 나머지를 전부
# UNKNOWN으로 뭉갠다. 그래서 A/B/C 계수는 측정할 재료가 없다고 생각했는데,
# UNKNOWN 234건의 설명을 다시 읽어보니 절반 이상이 상태를 말로 적고 있었다.
# ("3번정도 착화했습니다" -> A, "사용감 있어요" -> B, "밑창 마모 있음" -> C)
#
# 분류 순서가 곧 우선순위다:
#   하자 명시(C) > 착용 적음 명시(A, 단 사용감 언급이 없을 때) > 사용감 인정(B)
#   하자를 적은 매물은 "2번 신었다"고 해도 하자가 가격을 지배한다.
#
# 부정 표현을 먼저 지운다. "하자 없어요"에서 '하자'만 보면 상태 좋은 매물이
# C로 분류된다(실제로 그렇게 잘못 나온 것을 보고 추가했다).
#
# 검증: 같은 키워드 방식으로 새상품류를 분류해 비율을 재면 중앙값 0.778이 나오는데,
# 이는 crawl-time guess 기반의 DS 실측(0.778, n=63)과 독립적으로 일치한다.
import re

# "하자 없어요", "오염 하나 없고", "기스 전혀 X" 같은 부정 표현
NEGATED = re.compile(r"(하자|오염|얼룩|기스|스크래치|사용감|생활감|까짐|찢어짐|변색)"
                     r"\s*(하나|1도|은|는|이|가|도)?\s*(거의|전혀|별로)?\s*(없|x|X)")

# C: 하자를 명시한 표현
C_PATTERN = re.compile(r"하자|찢어|찢김|까짐|벗겨|뜯어|뜯김|구멍|갈라|터짐|밑창.{0,4}(닳|마모|분리)|"
                       r"박음질.{0,4}풀|오염.{0,3}(심|많)|얼룩.{0,3}(심|많)|눌림.{0,3}심|변색")

# B: 사용감을 인정한 표현
B_PATTERN = re.compile(r"사용감|생활감|착용감.{0,3}(있|많)|많이.{0,3}(신|착용)|자주.{0,3}(신|착용)|"
                       r"오염|얼룩|때탐|때가|기스|스크래치")

# A: 착용 횟수가 적음을 명시한 표현
A_PATTERN = re.compile(r"[1-9한두세]\s*[-~,]?\s*[1-9두세네]?\s*[회번]\s*(정도\s*)?(착용|착화|신)|"
                       r"몇\s*[회번]\s*(착용|착화|신)|실착\s*[1-9한두세]|"
                       r"상태\s*(아주\s*|매우\s*|되게\s*)?좋|깨끗|깔끔|새것\s*같|새신발\s*같")


def classify(text):
    """설명에서 상태 등급을 추정한다. 단서가 없으면 None."""
    if not text:
        return None
    text = NEGATED.sub(" ", text)
    if C_PATTERN.search(text):
        return "C"
    if A_PATTERN.search(text) and not B_PATTERN.search(text):
        return "A"
    if B_PATTERN.search(text):
        return "B"
    return None
